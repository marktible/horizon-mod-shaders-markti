def native_files(preset, record):
    files = {
        p.name: p.read_bytes() for p in sorted(NATIVE_SOURCE.iterdir()) if p.is_file()
    }
    source = files["horizon-shaders.toml"].decode()
    source = re.sub(
        r"(?m)^name = .*$", "name = " + json.dumps(record["name"]), source, count=1
    )
    source = re.sub(
        r"(?m)^version = .*$", "version = " + json.dumps(VERSION), source, count=1
    )
    values = {}
    if preset == "UltraPerformance":
        source = source.replace(
            'id = "markti_shaders"', 'id = "markti_shaders_ultra"', 1
        )
        source = source.replace("resolution = 2048", "resolution = 1024", 1).replace(
            "distance = 56.0", "distance = 48.0", 1
        )
        values = {
            "reflection_steps": 12,
            "water_ripples": 0.5,
            "surface_reflections": False,
            "ao_strength": 0.0,
            "pbr_materials": False,
            "water_caustics": False,
        }

    def option(match):
        text = match[0]
        key = re.search(r'(?m)^id = "([^"]+)"', text)[1]
        if key in values:
            text = re.sub(
                r"(?m)^default = .*$",
                "default = " + json.dumps(values[key]),
                text,
                count=1,
            )
        return text

    source = re.sub(r"(?ms)^\[\[options\]\]\n.*?(?=^\[|\Z)", option, source)
    files["horizon-shaders.toml"] = source.encode()
    options = {o["id"]: o["default"] for o in tomllib.loads(source)["options"]}
    return files, options


def write_archive(output, files):
    with zipfile.ZipFile(
        output, "w", compression=zipfile.ZIP_DEFLATED, compresslevel=9
    ) as archive:
        for name, data in sorted(files.items()):
            info = zipfile.ZipInfo(name, date_time=(2026, 1, 1, 0, 0, 0))
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = 0o100644 << 16
            info.create_system = 3
            archive.writestr(info, data, compresslevel=9)


def mod_files(native_id, files):
    """An unpacked .hnmod keeps its hook-version contract in GitHub installs."""
    mod_id = native_id + "_mod"
    crate_name = mod_id.replace("_", "-") + "-installer"
    prefix = f"mixins/{mod_id}/"
    identity = {
        "schema": 1,
        "id": mod_id,
        "version": VERSION,
        "game": "26.3",
        "horizon": HORIZON_REVISION,
        "mixins": MIXINS_REVISION,
        "hooks": 326,
    }
    manifest = f'''# Generated by tools/package.py; edit native-mod/installer.rs or the pack source.
[mod]
id = "{mod_id}"
version = "{VERSION}"

[compatibility]
horizon_revision = "{HORIZON_REVISION}"

[api]
path = "api"
'''
    library = f'''// Generated by tools/package.py. Horizon calls frame on the title screen too.
use horizon_client::mod_api::{{FrameEvent, Hooks, Host}};
mod payload;

pub fn hooks() -> Box<dyn Hooks> {{
    Box::new(Markti)
}}

struct Markti;

impl Hooks for Markti {{
    fn frame(&self, host: &mut dyn Host, _event: &mut FrameEvent) {{
        static INSTALLED: std::sync::Once = std::sync::Once::new();
        INSTALLED.call_once(|| {{
            if let Err(error) = payload::install(&host.instance_dir()) {{
                eprintln!("{mod_id}: could not install shader pack: {{error}}");
            }}
        }});
    }}
}}
'''
    embedded = "\n".join(
        f'    ("{name}", include_bytes!("../data/pack/{name}")),'
        for name in sorted(files)
    )
    payload = f"""// Generated by tools/package.py; shared implementation is native-mod/installer.rs.
#[path = "installer.rs"]
mod installer;

const FILES: &[(&str, &[u8])] = &[
{embedded}
];

pub fn install(instance: &std::path::Path) -> std::io::Result<()> {{
    installer::install_files(instance, "native-{mod_id}", FILES)
}}
"""
    result = {
        "horizon-native.json": (json.dumps(identity, indent=2) + "\n").encode(),
        prefix + "horizon-mixin.toml": manifest.encode(),
        prefix + "LICENSE": (ROOT / "LICENSE").read_bytes(),
        prefix + "api/Cargo.toml": (
            f'[package]\nname = "{crate_name}"\nversion = "{VERSION}"\n'
            'edition = "2024"\nlicense = "MIT"\npublish = false\n\n'
            "[dependencies]\n"
            'horizon-client = { git = "https://github.com/horizon-rust/horizon", '
            f'rev = "{HORIZON_REVISION}" }}\n'
        ).encode(),
        prefix + "api/src/lib.rs": library.encode(),
        prefix + "api/src/payload.rs": payload.encode(),
        prefix + "api/src/installer.rs": (
            ROOT / "native-mod/installer.rs"
        ).read_bytes(),
    }
    result.update({prefix + "api/data/pack/" + n: b for n, b in files.items()})
    return mod_id, result


def build():
    dist = ROOT / "dist"
    dist.mkdir(exist_ok=True)
    results = []
    mods = []
    for preset, record in PRESETS.items():
        output = dist / record["file"]
        with zipfile.ZipFile(
            output, "w", compression=zipfile.ZIP_DEFLATED, compresslevel=9
        ) as archive:
            for path in sorted(p for p in SOURCE.rglob("*") if p.is_file()):
                name = path.relative_to(SOURCE).as_posix()
                data = path.read_bytes()
                if name == "shaders/lib/settings.glsl":
                    source = data.decode()
                    for key, value in record["settings"].items():
                        source, count = re.subn(
                            r"(?m)^(#define " + key + r" )\S+",
                            lambda match: match[1] + value,
                            source,
                        )
                        if count != 1:
                            raise ValueError(
                                f"Expected exactly one definition of {key}"
                            )
                    data = source.encode()
                info = zipfile.ZipInfo(name, date_time=(2026, 1, 1, 0, 0, 0))
                info.compress_type = zipfile.ZIP_DEFLATED
                info.external_attr = 0o100644 << 16
                info.create_system = 3
                archive.writestr(info, data, compresslevel=9)
        results.append(
            {
                "file": output.name,
                "name": record["name"],
                "preset": preset,
                "format": "glsl",
                "bytes": output.stat().st_size,
                "sha256": hashlib.sha256(output.read_bytes()).hexdigest(),
                "settings": record["settings"],
            }
        )
        print(output.relative_to(ROOT))
        native_id = (
            "markti_shaders_ultra" if preset == "UltraPerformance" else "markti_shaders"
        )
        native_output = dist / (native_id + ".hshader")
        files, values = native_files(preset, record)
        write_archive(native_output, files)
        results.append(
            {
                "file": native_output.name,
                "name": record["name"],
                "preset": preset,
                "format": "native",
                "bytes": native_output.stat().st_size,
                "sha256": hashlib.sha256(native_output.read_bytes()).hexdigest(),
                "settings": values,
            }
        )
        print(native_output.relative_to(ROOT))
        mod_id, sources = mod_files(native_id, files)
        # Commit the unpacked sources: Add from GitHub scans these before any build.
        source_root = ROOT / "native-mod/bundles" / mod_id
        for old in source_root.rglob("*"):
            if old.is_file() and old.relative_to(source_root).as_posix() not in sources:
                old.unlink()
        for name, data in sources.items():
            destination = source_root / name
            destination.parent.mkdir(parents=True, exist_ok=True)
            if not destination.is_file() or destination.read_bytes() != data:
                destination.write_bytes(data)
        mod_output = dist / (mod_id + ".hnmod")
        write_archive(mod_output, sources)
        mods.append(
            {
                "id": mod_id,
                "name": record["name"],
                "file": mod_output.name,
                "preset": preset,
                "hooks": 326,
                "source": source_root.relative_to(ROOT).as_posix(),
                "shader_folder": "native-" + mod_id,
                "bytes": mod_output.stat().st_size,
                "sha256": hashlib.sha256(mod_output.read_bytes()).hexdigest(),
            }
        )
        print(mod_output.relative_to(ROOT))
    manifest = {
        "name": "Markti Shaders",
        "version": VERSION,
        "format": "Horizon native mods (.hnmod), native shader packs (.hshader), GLSL compatibility ZIPs",
        "recommended_format": "native",
        "requires_custom_client": False,
        "tested_horizon": TESTED_HORIZON,
        "settings": "Horizon Shader Options; stable ZIP filenames retain sidecars across updates",
        "packs": results,
        "mods": mods,
    }
    (dist / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
    (dist / "SHA256SUMS").write_text(
        "".join(f"{r['sha256']}  {r['file']}\n" for r in [*results, *mods])
    )


if __name__ == "__main__":
    build()
